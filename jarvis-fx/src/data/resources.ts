/**
 * Arsenal ledger – every resource from the research report (plus a few infrastructure extras),
 * with its licence, a licence flag and how JARVIS FX actually uses it.
 *
 * `usage` and `where` were set by scanning src/ (imports, meta.ts tech/source fields, port headers)
 * and package.json. `fxMatch` additionally links gallery effects live: the Arsenal view matches it
 * against every registered effect's meta (tech, source, licence), so new effects show up on their own.
 *
 * `where` tokens:  view:<ViewId>  ·  fx:<effectId>  ·  code:<path under src/ or repo root>
 */
import type { ViewId } from '@/lib/store'

export type LicenseFlag = 'ok' | 'care' | 'avoid'
export type Usage = 'code' | 'reference' | 'excluded'
export type ResourceCategory = 'ui' | 'motion' | '3d' | 'fx' | 'icons' | 'data' | 'fonts' | 'sound' | 'templates' | 'lists' | 'infra'

export interface Resource {
  id: string
  name: string
  url: string
  category: ResourceCategory
  /** licence as published by the author (SPDX id where one exists) */
  license: string
  licenseFlag: LicenseFlag
  usage: Usage
  /** places in this app that use it (see token format above) */
  where: string[]
  /** links gallery effects whose meta mentions the resource (case-insensitive) */
  fxMatch?: RegExp
  /** npm packages through which the resource enters the bundle */
  pkg?: string[]
  /** Polish note: what for / why not / caveats */
  note: string
  /** how the licence was checked, when it was verified in this project */
  verified?: string
  /** not part of the original research report (infrastructure we added) */
  extra?: boolean
}

